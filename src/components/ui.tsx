export function Alert({
  tone = "neutral",
  title,
  children,
}: {
  tone?: Exclude<Tone, "accent"> | "accent";
  title?: string;
  children?: ReactNode;
}) {
  const icon: IconName = tone === "success" ? "check" : tone === "neutral" || tone === "accent" ? "sparkles" : "alert";
  return (
    <div role={tone === "danger" ? "alert" : "status"} className={cn("flex gap-3 rounded-xl border px-3.5 py-3 text-sm", tones[tone])}>
      <Icon name={icon} className="mt-0.5 shrink-0" />
      <div className="min-w-0">
        {title && <p className="font-medium">{title}</p>}
        {children && <div className={cn(title && "mt-0.5", "opacity-90")}>{children}</div>}
      </div>
    </div>
  );
}
